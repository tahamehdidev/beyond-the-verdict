"""Phase C: build the error-analysis sample and a readable worksheet (no model calls, reads caches and predictions only).

    python -m src.error_analysis

Sample: unsafe errors of the baseline P0 (a decisive Supports/Refutes verdict that differs from gold), SAMPLE_PER_CLASS per gold
class, drawn with the seeded RNG. Case-study candidates: two correct decisive verdicts kept by the proposed policy P3 (one
gold S, one gold R) and the two most confident unsafe errors that P3 did NOT withhold. Labels (error types) are assigned by reading
the worksheet; they are written by hand to results/error_analysis/labels.csv, never by this script.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.config import load_config  # noqa: E402

SAMPLE_PER_CLASS = 8
SNIPPET_CHARS = 130
CLASSES = "SRCN"


def read_jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").split("\n") if line.strip()]


def main() -> int:
    cfg = load_config()
    k, ans_v, dec_v = cfg["retrieval"]["k"], cfg["prompt_versions"]["answer"], cfg["prompt_versions"]["decompose"]
    pred = pd.read_csv(ROOT / "results/eval_final/predictions.csv")
    unsafe = pred[pred["verdict"].isin([0, 1]) & (pred["verdict"] != pred["gold"])]
    rng = np.random.default_rng(cfg["seeds"]["bootstrap"])
    picks = []
    for g in range(4):
        pool = unsafe[unsafe["gold"] == g].sort_values("uid")
        idx = rng.choice(len(pool), size=min(SAMPLE_PER_CLASS, len(pool)), replace=False)
        picks.append(pool.iloc[sorted(idx)].assign(role="sampled_error"))
    sample = pd.concat(picks)
    kept = pred[(pred["withheld_P3_proposed"] == 0)]
    good = kept[kept["verdict"].isin([0, 1]) & (kept["verdict"] == kept["gold"])]
    successes = pd.concat([good[good["gold"] == g].sort_values("uid").sample(1, random_state=cfg["seeds"]["bootstrap"]) for g in (0, 1)])
    failures = kept[kept["verdict"].isin([0, 1]) & (kept["verdict"] != kept["gold"])].sort_values("cal_conf", ascending=False).head(2)
    cases = pd.concat([successes.assign(role="case_success"), failures.assign(role="case_failure")])
    allrows = pd.concat([sample, cases])

    claims = {s: json.loads((ROOT / cfg["paths"][f"{s}_claims"]).read_text(encoding="utf-8")) for s in ("dev", "train")}
    dec = {r["uid"]: r for r in read_jsonl(ROOT / cfg["paths"]["cache"] / "decompose.jsonl")
           if r["prompt_version"] == dec_v and r["status"] == "ok"}
    ret = {r["uid"]: r["results"] for r in read_jsonl(ROOT / cfg["paths"]["cache"] / "retrieve.jsonl") if r["k"] == k}
    ans = {}
    for r in read_jsonl(ROOT / cfg["paths"]["cache"] / "answer.jsonl"):
        if r["prompt_version"] == ans_v and r.get("k", 5) == k:
            ans[(r["uid"], r["qidx"])] = r["label"]

    out_dir = ROOT / "results" / "error_analysis"
    out_dir.mkdir(parents=True, exist_ok=True)
    allrows[["uid", "role", "subset", "gold_name", "verdict_name", "state_name", "cal_conf",
             "withheld_P3_proposed", "t_yes", "t_no", "t_unv", "f_yes", "f_no", "f_unv"]].to_csv(
        out_dir / "sample.csv", index=False, float_format="%.4f")
    lines = ["# Error-analysis worksheet (generated by src/error_analysis.py; evaluation claims, no labels assigned here)\n"]
    for n, (_, row) in enumerate(allrows.iterrows(), 1):
        split = row["uid"].split("-")[0]
        c = claims["dev" if split == "dev" else "train"][int(row["uid"].split("-")[1])]
        lines.append(f"\n## Case {n}: {row['uid']} [{row['role']}]")
        lines.append(f"CLAIM: {c['claim']}")
        lines.append(f"GOLD: {row['gold_name']} | VERDICT: {row['verdict_name']} (cal_conf {row['cal_conf']:.2f}) | STATE: {row['state_name']} "
                     f"| P3 withheld: {bool(row['withheld_P3_proposed'])}")
        lines.append(f"COUNTS true-frame Y/N/U {row['t_yes']}/{row['t_no']}/{row['t_unv']}, false-frame Y/N/U {row['f_yes']}/{row['f_no']}/{row['f_unv']}")
        lines.append(f"GOLD JUSTIFICATION: {(c.get('justification') or '')[:260]}")
        for q, qd in enumerate(dec[row["uid"]]["questions"]):
            snip = ret[row["uid"]][q]
            top = snip[0]["text"].replace("\n", " ")[:SNIPPET_CHARS] if snip else "(none)"
            lines.append(f"- Q{q} [{qd['frame']}] {qd['q']} -> {ans[(row['uid'], q)]} | top: {top}")
    (out_dir / "worksheet.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"unsafe errors total {len(unsafe)}; sampled {len(sample)}; case candidates {len(cases)}; written to {out_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
